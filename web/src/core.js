export function toSpoken(text) {
  let s = text;
  for (const k of YOMI_KEYS) s = s.split(k).join(YOMI[k]);
  return s.replace(/、/g, "、 ") + "。";
}

export function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

export const BOARD_CHOICES = [12, 18, 24, 30];
export const BOARD_DEFAULT = 18;

/* 指定の枚数を、基礎4割・標準3.5割・難2.5割の割合で抜き出す */
export function drawBoard(pool, total) {
  const n = total || BOARD_DEFAULT;
  const want = [Math.round(n * 0.4), Math.round(n * 0.35)];
  want.push(n - want[0] - want[1]);
  let picked = [];
  for (let lv = 1; lv <= 3; lv++) {
    picked = picked.concat(shuffle(pool.filter((c) => c.l === lv)).slice(0, want[lv - 1]));
  }
  // 足りなければ残りから補う
  if (picked.length < n) {
    const rest = shuffle(pool.filter((c) => !picked.includes(c)));
    picked = picked.concat(rest.slice(0, n - picked.length));
  }
  return shuffle(picked).map((c, i) => ({ ...c, id: i + "-" + c.a }));
}

/* 枚数に応じた暗記の秒数 */
export function memoSeconds(total) {
  return Math.max(18, Math.min(48, Math.round((total || BOARD_DEFAULT) * 1.4)));
}



/* ============================================================
   読み札の音声
   事前に作った音声ファイルがあればそれを鳴らし、
   無ければ端末の合成音声に切り替える。
   ファイル名は読み札の文から機械的に決まるので、
   答えの札の名前は表に出ない。
   ============================================================ */

export function clueKey(text) {
  let h = 5381;
  for (let i = 0; i < text.length; i++) h = ((h * 33) ^ text.charCodeAt(i)) >>> 0;
  return h.toString(36);
}

export function speakClue(text, opt = {}) {
  const rate = opt.rate || 1.0;
  const pitch = opt.pitch != null ? opt.pitch : 1.06;
  let stopped = false;
  let started = false;
  let audio = null;

  const fallback = () => {
    if (stopped || started) return;
    started = true;
    if (typeof window === "undefined" || !window.speechSynthesis) return;
    try {
      window.speechSynthesis.cancel();
      const u = new SpeechSynthesisUtterance(toSpoken(text));
      u.lang = "ja-JP";
      u.rate = rate;
      u.pitch = pitch;
      if (opt.voice) u.voice = opt.voice;
      window.speechSynthesis.speak(u);
    } catch (e) {}
  };

  try {
    audio = new Audio("voice/" + clueKey(text) + ".mp3");
    audio.preload = "auto";
    audio.oncanplaythrough = () => {
      if (stopped || started) return;
      started = true;
      audio.playbackRate = rate;
      audio.play().catch(() => {
        started = false;
        fallback();
      });
    };
    audio.onerror = fallback;
    audio.load();
  } catch (e) {
    fallback();
  }

  // 用意できなければ合成音声に切り替える
  const guard = setTimeout(fallback, 1200);

  return () => {
    stopped = true;
    clearTimeout(guard);
    try {
      if (audio) audio.pause();
      if (window.speechSynthesis) window.speechSynthesis.cancel();
    } catch (e) {}
  };
}


