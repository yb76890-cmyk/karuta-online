export const FEEDBACK_URL = "";

/* 端末や画面の情報を添えて開く。
   どの環境で起きた不具合かが分かり、切り分けが早くなる。 */
export function openFeedback() {
  if (!FEEDBACK_URL) return;
  let url = FEEDBACK_URL;
  try {
    const info = [
      window.innerWidth + "x" + window.innerHeight,
      navigator.language,
      (navigator.userAgent || "").slice(0, 120),
    ].join(" / ");
    // フォームに「環境」の記述欄を作り、その entry.数字 をここに入れると自動で埋まる
    const ENTRY_ID = "";
    if (ENTRY_ID) {
      url += (url.includes("?") ? "&" : "?") + "usp=pp_url&" + ENTRY_ID + "=" + encodeURIComponent(info);
    }
  } catch (e) {}
  window.open(url, "_blank", "noopener");
}
